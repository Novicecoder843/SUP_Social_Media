const express = require("express");
const router = express.Router();

const storyController =
  require("../controllers/story.controller");

const auth =
  require("../middleware/auth");

const upload =
  require("../middleware/storyUpload");

/////////////////////////////////////////////////////
// 📸 UPLOAD STORY
/////////////////////////////////////////////////////
router.post(
  "/upload",
  auth,
  upload.any(),
  storyController.uploadStory
);
// router.post(
//   "/upload",
//   auth,
//   upload.single("media"),
//   storyController.uploadStory
// );

/////////////////////////////////////////////////////
// 📖 GET ALL STORIES
/////////////////////////////////////////////////////

router.get(
  "/",
  auth,
  storyController.getStories
);

/////////////////////////////////////////////////////
// 👀 VIEW STORY
/////////////////////////////////////////////////////

router.post(
  "/view/:id",
  auth,
  storyController.viewStory
);

/////////////////////////////////////////////////////
// ❤️ LIKE STORY
/////////////////////////////////////////////////////

router.post(
  "/like/:id",
  auth,
  storyController.likeStory
);

/////////////////////////////////////////////////////
// 💬 REPLY STORY
/////////////////////////////////////////////////////

router.post(
  "/reply/:id",
  auth,
  storyController.replyStory
);

/////////////////////////////////////////////////////
// 👥 STORY VIEWERS
/////////////////////////////////////////////////////

router.get(
  "/viewers/:id",
  auth,
  storyController.getStoryViewers
);

/////////////////////////////////////////////////////
// 🗑 DELETE STORY
/////////////////////////////////////////////////////

router.delete(
  "/:id",
  auth,
  storyController.deleteStory
);

module.exports = router;
